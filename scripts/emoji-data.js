#!/usr/bin/env node
'use strict';
// Builds media/emoji-data.js, the reaction picker's emoji, from Unicode's emoji-test.txt:
//   curl -sSfL https://unicode.org/Public/emoji/latest/emoji-test.txt -o /tmp/emoji-test.txt
//   node scripts/emoji-data.js /tmp/emoji-test.txt
// Fully-qualified emoji only, no skin-tone variants and no components, up to MAX_VERSION so they show on most systems.
// An emoji that takes a skin tone as one added modifier is marked with a trailing ~ ("👍~ thumbs up").
const fs = require('fs');
const path = require('path');

const MAX_VERSION = 15.1;
const src = process.argv[2];
if (!src) { process.stderr.write('usage: node scripts/emoji-data.js <emoji-test.txt>\n'); process.exit(1); }

const LINE = /^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$/;
const lines = fs.readFileSync(src, 'utf8').split('\n');
const all = new Set(lines.map((l) => LINE.exec(l)).filter(Boolean).map((m) => m[1]));
const toneable = (e) => all.has(e.replace(/\uFE0F/g, '') + '\u{1F3FD}');
const groups = [];
let group = null;
for (const line of lines) {
  const g = /^# group: (.+)$/.exec(line);
  if (g) { group = g[1] === 'Component' ? null : { name: g[1], items: [] }; if (group) groups.push(group); continue; }
  // 1F600 ; fully-qualified # 😀 E1.0 grinning face
  const m = LINE.exec(line);
  if (!m || !group) continue;
  const [, emoji, version, name] = m;
  if (Number(version) > MAX_VERSION || /skin tone/.test(name)) continue;
  group.items.push(`${emoji}${toneable(emoji) ? '~' : ''} ${name.replace(/\|/g, ' ')}`);
}
const data = groups.filter((x) => x.items.length).map((x) => [x.name, x.items.join('|')]);
const out = path.join(__dirname, '..', 'media', 'emoji-data.js');
const header = '// Generated by scripts/emoji-data.js from Unicode\'s emoji-test.txt (Unicode License v3, see LICENSE): [group, "emoji name|…"];\n// a ~ after an emoji means it takes a skin tone.\n';
fs.writeFileSync(out, `${header}window.CHIRP_EMOJI = ${JSON.stringify(data)};\n`);
process.stdout.write(`${out}: ${data.reduce((n, x) => n + x[1].split('|').length, 0)} emoji in ${data.length} groups\n`);
